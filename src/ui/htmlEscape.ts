/**
 * Presentation layer: the one place that escapes untrusted text before it is
 * interpolated into the dashboard webview's inline HTML.
 */

export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
